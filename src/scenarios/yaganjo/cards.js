/**
 * 한글 카드번호를 코드에서 부르기 위한 ASCII 이름.
 * 사상표의 키는 마크다운 원문 그대로 두고(대조가 글자 단위로 성립해야 한다),
 * 별칭은 여기에만 둔다. codeOf/cardOf 가 알아서 풀어 준다.
 */
export const CARD_ALIASES = {
  PUB1: '공개①',
  PUB2: '공개②',
};

// 역방향을 만들면서 값(코드)이 겹치는지도 함께 본다.
// 한 코드에 두 카드 번호가 붙으면 역방향이 조용히 한쪽을 덮어써서,
// QR 이 엉뚱한 카드를 가리키는 사고가 소리 없이 지나간다.
function buildCodeToCard(map) {
  const out = {};
  for (const card of Object.keys(map)) {
    const code = map[card];
    if (out[code]) {
      throw new Error(`[yaganjo/cards] 단서 코드 중복: '${code}' 가 ${out[code]} 와 ${card} 양쪽에 붙어 있다.`);
    }
    out[code] = card;
  }
  return out;
}

/** 단서 코드 → 보드 카드번호. cardToCode 의 역방향. 109행. */
export const codeToCard = buildCodeToCard(cardToCode);

/** 보드 카드번호(별칭 허용) → 단서 코드. 없으면 null. */
export function codeOf(cardNo) {
  const key = CARD_ALIASES[cardNo] || cardNo;
  return cardToCode[key] || null;
}

/** 단서 코드 → 보드 카드번호. 없으면 null(방 항목·앱 전용 코드는 카드가 아니다). */
export function cardOf(code) {
  return codeToCard[code] || null;
}

/** 발급표가 선언한 행 수. 파서가 뽑은 카드 수와 이 값을 대조한다. */
export const CARD_COUNT = Object.keys(cardToCode).length;

export default cardToCode;
