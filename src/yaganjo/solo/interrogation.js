const clueReactOf = (sid, code) => CLUE_REACT[sid]?.[code];

/** 이 인물과 '관련 있는' 증거 코드 집합(모순·반응에 쓰이는 코드) — 제시 목록 필터용. */
export function relatedCodes(sid) {
  const d = DATA[sid];
  const set = new Set();
  if (!d) return set;
  for (const s of d.statements) {
    if (s.contradict) (s.contradict.codes || [s.contradict.code]).forEach((c) => c && set.add(c));
    if (s.soft) Object.keys(s.soft).forEach((c) => set.add(c));
  }
  Object.keys(CLUE_REACT[sid] || {}).forEach((c) => set.add(c)); // 인물 단위 대질 반응 코드도 관련 단서로
  return set;
}

const needsOf = (s) => (Array.isArray(s.needs) ? s.needs : [s.needs]).filter(Boolean);

/** 이 인물에게 열려 있는 '화제' — 그 주제 단서를 하나라도 챙기면 질문지에 질문이 생긴다. */
export function visibleTopics(sid, collected) {
  const have = new Set(collected || []);
  return (TOPICS[sid] || []).filter((t) => t.codes.some((c) => have.has(c)));
}

/** 그 화제로 이어서 물어볼 수 있는 단서 — 보유했고 반응이 있는 것만.
 *  같은 화제의 질문을 여는 단서(needs)는 빼둔다 — 「졸피뎀 약통은 뭐죠?」 옆에
 *  「'졸피뎀 약통'에 대해 묻는다」가 나란히 뜨면 같은 걸 두 번 묻는 셈이다. */
export function topicClues(sid, topic, collected, statements) {
  const have = new Set(collected || []);
  const viaQuestion = new Set(
    topicStatements(sid, topic, statements).flatMap((s) => needsOf(s)),
  );
  return (topic?.codes || []).filter((c) => have.has(c) && !viaQuestion.has(c)
    && clueTalkable(sid, statements, c));
}

/** 이 질문이 딸린 화제 — needs 코드가 여러 화제에 걸치면 '먼저 정의된' 화제 하나만 주인이 된다.
 *  (한 질문이 두 화제에 동시에 뜨면 어느 쪽에서 물었는지 헷갈리고 목록만 길어진다) */
export function topicOfStatement(sid, s) {
  if (!s || s.hidden || s.root || !s.needs) return null;  // root:true = 화제에 묻지 말고 최상위 고정
  const codes = needsOf(s);
  return (TOPICS[sid] || []).find((t) => codes.some((c) => t.codes.includes(c))) || null;
}

/** 이 화제에 딸린 질문 — 단서로 열리는 질문(needs)은 그 단서가 속한 화제 밑으로 들어간다.
 *  요힘빈 통을 주웠다고 「운동」 화제와 「요힘빈은 누구 겁니까?」가 나란히 뜨면 안 된다.
 *  화제 하나만 뜨고, 파생 질문은 그 안에서 이어지게 한다. */
export function topicStatements(sid, topic, statements) {
  return (statements || []).filter((s) => topicOfStatement(sid, s)?.id === topic?.id);
}

/** 최상위에 남는 질문 — 기본 질문과, 모순으로 열린 질문(놓치면 안 되는 진전). */
export function rootStatements(sid, statements) {
  return (statements || []).filter((s) => !topicOfStatement(sid, s));
}

/** 지금 이 인물에게 그 단서로 '물어볼 말'이 있는가 — 질문지의 「단서」 칸에 올릴지 판단.
 *  진술에 걸린 반응(모순·soft)이나 인물 단위 대질 반응이 하나라도 있어야 올린다 →
 *  목록에 오른 단서는 반드시 무슨 말이든 듣게 된다(막다른 길 없음). */
export function clueTalkable(sid, statements, code) {
  return !!clueTargetIn(statements, code) || !!clueReactOf(sid, code);
}

/** 심문 인사말 — 2차(phase 2)면 재방문 멘트. */
export const introOf = (sid, phase = 1) => {
  const d = DATA[sid];
  if (!d) return '';
  return phase >= 2 ? (d.intro2 || d.intro) : d.intro;
};

/** 현재 노출되는 질문(진술): phase 이하 + 기본(always) + needs 충족(배열=하나라도) + hidden 해금. */
export function visibleStatements(sid, collected = [], unlocked = [], phase = 1) {
  const d = DATA[sid];
  if (!d) return [];
  const have = new Set(collected);
  const open = new Set(unlocked);
  return d.statements.filter((s) => {
    if ((s.phase || 1) > phase) return false;
    if (s.hidden) return open.has(s.id);
    if (s.needs) {
      const list = Array.isArray(s.needs) ? s.needs : [s.needs];
      return list.some((c) => have.has(c));
    }
    return true;
  }).map((s) => voiced(s, open));
}

/** 캐묻기 → { text, unlock?, grants? } (grants: 대화로 확보되는 증언 단서 코드) */
// 밝힌 뒤 말투 — 진술에 after: { when, text?, press? } 가 있으면, when 진술이 열린(unlocked) 인물에게는
//   그 문장으로 바꿔 보인다. 흐엉은 여권을 밝힌 뒤 또렷한 한국어로 말하는데, 단계 3 문장이 다시 서툰 말투로
//   돌아가던 것(시트 「바꾼 뒤에는 되돌아가지 않는다」, 6회차 #2).
function voiced(s, open) {
  if (!s || !s.after || !open.has(s.after.when)) return s;
  return { ...s, text: s.after.text ?? s.text, press: s.after.press ?? s.press };
}
export function pressOf(sid, stId, unlocked = []) {
  const s = voiced(stOf(sid, stId), new Set(unlocked));
  if (!s) return { text: '' };
  return { text: s.press || '…(더 할 말이 없다.)', unlock: s.pressUnlock, grants: GRANTS[sid]?.[stId] };
}

/** 단서로 '질문'하면 반응할 (지금 보이는) 진술을 찾는다 — 모순(contradict) 우선, 없으면 반응(soft).
 *  visibleStatements 결과만 대상으로 하므로 아직 안 열린 진술로 건너뛰지 않는다(추리 순서 보존). */
export function clueTargetIn(statements, code) {
  let soft = null;
  for (const s of statements) {
    const codes = s.contradict ? (s.contradict.codes || [s.contradict.code]) : [];
    if (codes.includes(code)) return { stId: s.id, kind: 'contradict' };
    if (!soft && s.soft && s.soft[code]) soft = { stId: s.id, kind: 'soft' };
  }
  return soft;
}

/** 이 인물의 '다른 진술'이 쓰는 코드인가 — 관련은 있는데 지금 이 진술이 아닐 때를 가리기 위한 것.
 *  hidden 은 뺀다 — 아직 열리지도 않은 질문을 가리키면 없는 곳을 찾아 헤매고,
 *  덤으로 '이 증거가 이 사람에게 언젠가 쓸모 있다'는 사실까지 공짜로 알려준다. */
function usedInOtherStatement(sid, stId, code) {
  const d = DATA[sid];
  if (!d) return false;
  return d.statements.some((s) => {
    if (s.id === stId || s.hidden) return false;
    const codes = s.contradict ? (s.contradict.codes || [s.contradict.code]) : [];
    return codes.includes(code) || !!(s.soft && s.soft[code]);
  });
}

/** 증거 제시 → { result: 'contradict'|'soft'|'offtopic'|'wrong', text, unlock?, confess?, grants? }
 *  우선순위: (진술별) 모순 > 진술별 반응 > (인물 단위) 대질 반응 > 다른 진술 몫 > 무관. stId=null이면 인물 반응만.
 *  confessed=true(이미 관여 자백)면 인물 반응에 afterConfess 변형이 있으면 인정 톤으로 대체. */
export function presentOn(sid, stId, code, confessed = false) {
  const s = stOf(sid, stId);
  if (s) {
    const codes = s.contradict ? (s.contradict.codes || [s.contradict.code]) : [];
    if (codes.includes(code)) {
      // textBy[code] 가 있으면 그걸 쓴다 — codes 가 OR 이라 어느 걸로 짚었는지에 따라
      //   수사관이 단정할 수 있는 범위가 다르다(감식 결과를 아직 안 받았는데 "요힘빈이
      //   검출됐다"고 말해버리면, 나중에 도착하는 감식이 김빠진 반복이 된다).
      return { result: 'contradict', text: s.contradict.textBy?.[code] || s.contradict.text,
        unlock: s.contradict.unlock, confess: !!s.contradict.confess, grants: s.contradict.grants };
    }
    if (s.soft && s.soft[code]) {
      const v = s.soft[code];
      return typeof v === 'string' ? { result: 'soft', text: v } : { result: 'soft', text: v.text, grants: v.grants };
    }
  }
  const react = clueReactOf(sid, code);
  if (react) {
    if (typeof react === 'string') return { result: 'soft', text: react };
    const text = (confessed && react.afterConfess) ? react.afterConfess : react.text;
    return { result: 'soft', text, grants: react.grants, unlock: react.unlock };
  }
  // 이 사람의 다른 진술이 쓰는 코드다 — 10:10 CCTV 를 오후 행적에 낸 꼴이라, 정답 증거인데
  //   엉뚱한 대답에 붙인 것뿐이다. 'wrong'(신뢰도 −1)으로 벌하지 않고 갈 곳만 일러 준다.
  //   화제 경로(askAboutClue)가 이미 감점 없이 안내하고 있어, 반박 경로만 관용도가 달랐다.
  if (usedInOtherStatement(sid, stId, code)) {
    return { result: 'offtopic', text: '(…그 얘기라면 지금 이 대답에 꺼낼 게 아닌 것 같다.)' };
  }
  return { result: 'wrong', text: '' };
}
