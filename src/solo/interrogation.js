/** 이 인물과 '관련 있는' 증거 코드 집합(모순·반응에 쓰이는 코드) — 제시 목록 필터용. */
export function relatedCodes(sid) {
  const d = DATA[sid];
  const set = new Set();
  if (!d) return set;
  for (const s of d.statements) {
    if (s.contradict) (s.contradict.codes || [s.contradict.code]).forEach((c) => c && set.add(c));
    if (s.soft) Object.keys(s.soft).forEach((c) => set.add(c));
  }
  return set;
}

/** 심문 인사말 — 2차(phase 2)면 재방문 멘트. */
export const introOf = (sid, phase = 1) => {
  const d = DATA[sid];
  if (!d) return '';
  return phase >= 2 ? (d.intro2 || d.intro) : d.intro;
};

/** 현재 노출되는 질문(진술): phase 이하 + 기본(always) + needs 충족(배열=하나라도) + hidden 해금. */
export function visibleStatements(sid, collected = [], unlocked = [], phase = 1) {
  const d = DATA[sid];
  if (!d) return [];
  const have = new Set(collected);
  const open = new Set(unlocked);
  return d.statements.filter((s) => {
    if ((s.phase || 1) > phase) return false;
    if (s.hidden) return open.has(s.id);
    if (s.needs) {
      const list = Array.isArray(s.needs) ? s.needs : [s.needs];
      return list.some((c) => have.has(c));
    }
    return true;
  });
}

/** 캐묻기 → { text, unlock?, grants? } (grants: 대화로 확보되는 증언 단서 코드) */
export function pressOf(sid, stId) {
  const s = stOf(sid, stId);
  if (!s) return { text: '' };
  return { text: s.press || '…(더 할 말이 없다.)', unlock: s.pressUnlock, grants: GRANTS[sid]?.[stId] };
}

/** 증거 제시 → { result: 'contradict'|'soft'|'wrong', text, unlock?, confess? } */
export function presentOn(sid, stId, code) {
  const s = stOf(sid, stId);
  if (!s) return { result: 'wrong', text: '' };
  const codes = s.contradict ? (s.contradict.codes || [s.contradict.code]) : [];
  if (codes.includes(code)) {
    return { result: 'contradict', text: s.contradict.text, unlock: s.contradict.unlock, confess: !!s.contradict.confess };
  }
  if (s.soft && s.soft[code]) return { result: 'soft', text: s.soft[code] };
  return { result: 'wrong', text: '' };
}
