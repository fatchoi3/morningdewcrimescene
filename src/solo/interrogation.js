const Q_TEXT = {}; // sid -> { id: q }
for (const [sid, d] of Object.entries(DATA)) {
  Q_TEXT[sid] = {};
  for (const c of COMMON) Q_TEXT[sid][c.id] = c.q;
  for (const e of d.extra) Q_TEXT[sid][e.id] = e.q;
}

/** 현재 노출 가능한 질문 목록(공통 + 조건 충족한 고유/꼬리/증거해금). */
export function availableQuestions(sid, askedIds = [], unlockedIds = []) {
  const d = DATA[sid];
  if (!d) return [];
  const asked = new Set(askedIds);
  const unlocked = new Set(unlockedIds);
  const out = COMMON.map((c) => ({ id: c.id, q: c.q, follow: false }));
  for (const e of d.extra) {
    if (e.hidden) { if (unlocked.has(e.id)) out.push({ id: e.id, q: e.q, follow: true }); continue; }
    if (e.after) { if (asked.has(e.after)) out.push({ id: e.id, q: e.q, follow: true }); continue; }
    out.push({ id: e.id, q: e.q, follow: false });
  }
  return out;
}

export const questionText = (sid, id) => Q_TEXT[sid]?.[id] || id;
export const answerOf = (sid, id) => DATA[sid]?.a?.[id] ?? (DATA[sid]?.extra.find((e) => e.id === id)?.a) ?? '…(대답이 없다.)';

/** 증거 들이밀기 반응. { a, unlock? } */
export function confrontOf(sid, code) {
  const c = DATA[sid]?.confront;
  if (!c) return { a: '…(반응이 없다.)' };
  return c[code] || { a: c._default };
}
